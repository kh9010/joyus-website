const written = [];
for (const old of PODCAST_OLD) {
  const m = bestPodcast(old.replace(/^\d+-/, ''));
  if (m) written.push(writeStub(`/thinking-on-thinking/${old}`, `/podcast/${m}.html`));
  else console.warn('  [skip] no podcast match for', old);
}
for (const [oldPath, target] of Object.entries(EXPLICIT)) {
  const rel = oldPath.replace(/^\//, '');
  // skip only if a real *file* already lives there (don't let a dir block us)
  if (exists(rel) && fs.statSync(path.join(ROOT, rel)).isFile()) { console.warn('  [skip] live file at', oldPath); continue; }
  written.push(writeStub(oldPath, target));
}
for (const slug of ['pathfinder', 'quiznext', 'misplaced-game', 'immersive-inclusive-audio-institute']) {
  if (!exists(`our-work/${slug}.html`)) written.push(writeStub(`/our-work/${slug}`, '/work/'));
}
if (!exists('musings/thinking-on-ai-over-the-seasons.html'))
  written.push(writeStub('/musings/thinking-on-ai-over-the-seasons', '/podcast.html'));

console.log(`redirects.js: ${podcast.length} podcast slugs indexed`);
console.log(`stub files written: ${written.length}`);
