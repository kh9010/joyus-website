// gen-redirects.mjs — old-URL redirect map + redirect stubs for joyus.studio
// ---------------------------------------------------------------------------
// The site moved off Squarespace. The old structure used different paths that
// now 404 on the new GitHub Pages site (which can't issue real HTTP 301s):
//
//   /thinking-on-thinking                 -> /podcast.html        (podcast index)
//   /thinking-on-thinking/<NNN>-<slug>    -> /podcast/<slug>.html (episodes)
//   /our-work/<slug>                      -> /work/...            (case studies)
//   /musings/<slug>                       -> /thinking/<slug>.html(essays)
//   a handful of old root pages           -> their new homes
//
// This script is the single source of truth for that mapping. It:
//   1. Reads the live files to build a podcast slug index.
//   2. Writes /redirects.js — tiny baked data the 404 page reads to forward ANY
//      old episode URL (incl. ones Google indexed but nobody's clicked yet) by
//      fuzzy-matching the slug. No match -> the normal "oops" 404 shows.
//   3. Writes redirect stub files (200 + canonical + meta-refresh) for the
//      finite, exactly-known old URLs — the cleanest SEO signal for those.
//
// Re-run after adding episodes/case studies:  node scripts/gen-redirects.mjs
// ---------------------------------------------------------------------------
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://joyus.studio';

const exists = (p) => fs.existsSync(path.join(ROOT, p));

// ── 1. Current slugs (for fuzzy-matching old episode / essay / case-study URLs) ─
const slugsIn = (dir, keep = () => true) => fs.readdirSync(path.join(ROOT, dir))
  .filter((f) => f.endsWith('.html'))
  .map((f) => f.slice(0, -5))
  .filter((s) => s !== 'index' && !/(^|-)old$/.test(s) && keep(s));

const podcast = slugsIn('podcast', (s) => s !== 'archive');
const thinking = slugsIn('thinking');
const work = slugsIn('work', (s) => !/-cut-/.test(s) && !/^case-/.test(s));

// ── 2. Explicit one-off old→new mappings (exact paths) ───────────────────────
// Keys are normalised: lowercased, no trailing slash. The runtime also accepts
// a trailing-slash form of each key.
const EXPLICIT = {
  '/thinking-on-thinking': '/podcast.html',
  '/joyus-services-and-offerings': '/services.html',
  '/about-us': '/about.html',
  // old root-level case-study pages now live under /work/
  '/agemo.html': '/work/agemo.html',
  '/agemo-cut-research.html': '/work/agemo-cut-research.html',
  '/agemo-cut-interface.html': '/work/agemo-cut-interface.html',
  '/klydo.html': '/work/klydo.html',
  '/convegenius.html': '/work/convegenius.html',
  '/rachna-nivas.html': '/work/rachna-nivas.html',
};

// ── 3. Write /redirects.js (runtime data for the 404 page) ───────────────────
const data = {
  exact: EXPLICIT,
  podcastBase: '/thinking-on-thinking', // /thinking-on-thinking/<NNN>-<slug>
  essayBase: '/musings',                // /musings/<slug> -> /thinking/<slug>.html
  workBase: '/our-work',                // /our-work/<slug> -> /work/<slug>.html or /work/
  legacyPrefix: '/joyus-website',       // pre-cutover GitHub Pages project path
  podcast, thinking, work,
};
fs.writeFileSync(
  path.join(ROOT, 'redirects.js'),
  '// AUTO-GENERATED by scripts/gen-redirects.mjs — do not hand-edit.\n' +
  'window.JOYUS_REDIRECTS = ' + JSON.stringify(data) + ';\n',
);

// ── 4. Fuzzy match (mirrors the runtime in 404.html) ─────────────────────────
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const toks = (s) => new Set(norm(s).split('-').filter(Boolean));
function bestPodcast(slug) {
  const want = norm(slug);
  const exact = podcast.find((p) => p === want);
  if (exact) return exact;
  const pref = podcast.find((p) => p.startsWith(want.slice(0, 40)) || want.startsWith(p.slice(0, 40)));
  if (pref) return pref;
  const wt = toks(want);
  let best = null, bestScore = 0;
  for (const p of podcast) {
    const pt = toks(p);
    let inter = 0; for (const t of wt) if (pt.has(t)) inter++;
    const score = inter / Math.max(wt.size, pt.size);
    if (score > bestScore) { bestScore = score; best = p; }
  }
  return bestScore >= 0.4 ? best : null;
}

// ── 5. Stub files (200 + canonical) for the finite, exactly-known old URLs ────
const STUB = (target) => `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Moved — Joyus Studio</title>
<link rel="canonical" href="${SITE}${target}">
<meta http-equiv="refresh" content="0; url=${SITE}${target}">
<script>location.replace("${SITE}${target}");</script>
</head>
<body style="font-family:system-ui,-apple-system,sans-serif;padding:2rem;color:#2C3544;background:#FAF7F2">
This page has moved — redirecting to <a href="${SITE}${target}">joyus.studio</a>…
</body>
</html>
`;
function writeStub(oldPath, target) {
  const base = oldPath.replace(/^\//, '');
  // Extensionless path that's also a real directory (e.g. /thinking-on-thinking,
  // which now holds episode stubs) must be served as <dir>/index.html, or GitHub
  // Pages 404s on the bare path. Otherwise a flat <path>.html serves at /<path>.
  let rel;
  if (oldPath.endsWith('.html')) rel = base;
  else if (exists(base) && fs.statSync(path.join(ROOT, base)).isDirectory()) rel = `${base}/index.html`;
  else rel = `${base}.html`;
  const full = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, STUB(target));
  return rel;
}

